#!/usr/bin/env node
// Scans public/ and writes src/assets.gen.ts: which stills, clips and music
// exist right now, with each clip's real length (ffprobe) so a shot can hold
// its last frame instead of running past the end of the file.
// Runs before `start`, `render` and `still`. Re-run after dropping new files.
import { execFileSync } from 'node:child_process'
import { existsSync, readdirSync, statSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const PUB = join(ROOT, 'public')
const FPS = 30

const list = (dir, exts, minBytes = 1024) => {
  const abs = join(PUB, dir)
  if (!existsSync(abs)) return []
  return readdirSync(abs)
    .filter((f) => exts.some((e) => f.toLowerCase().endsWith(e)))
    .filter((f) => statSync(join(abs, f)).size > minBytes) // skip empty / half-copied files
    .sort()
}

const probe = (file) => {
  try {
    const out = execFileSync(
      'ffprobe',
      ['-v', 'error', '-select_streams', 'v:0', '-show_entries', 'stream=width,height,nb_frames,r_frame_rate:format=duration', '-of', 'json', file],
      { encoding: 'utf8' },
    )
    const j = JSON.parse(out)
    const s = j.streams?.[0] ?? {}
    const duration = Number(j.format?.duration ?? 0)
    if (!s.width || !duration) return null
    return { width: s.width, height: s.height, durationInSeconds: duration }
  } catch {
    return null // unreadable file: treated as missing, the shot falls back
  }
}

const probeAudio = (file) => {
  try {
    const out = execFileSync('ffprobe', ['-v', 'error', '-show_entries', 'format=duration', '-of', 'json', file], { encoding: 'utf8' })
    const d = Number(JSON.parse(out).format?.duration ?? 0)
    return d > 0 ? d : null
  } catch {
    return null
  }
}

const stills = {}
for (const f of list('keyframes', ['.png', '.jpg', '.jpeg', '.webp'])) {
  const name = f.replace(/\.[^.]+$/, '')
  if (name.endsWith('-small')) continue
  stills[name] = `keyframes/${f}`
}

const clips = {}
for (const f of list('clips', ['.mp4', '.mov', '.webm'])) {
  const meta = probe(join(PUB, 'clips', f))
  if (!meta) continue
  const name = f.replace(/\.[^.]+$/, '')
  clips[name] = {
    src: `clips/${f}`,
    width: meta.width,
    height: meta.height,
    // last frame we can safely show (one frame of margin for rounding)
    durationInFrames: Math.max(1, Math.floor(meta.durationInSeconds * FPS) - 1),
  }
}

let music = null
const musicFile = join(PUB, 'audio', 'music.mp3')
if (existsSync(musicFile)) {
  const d = probeAudio(musicFile)
  if (d) music = { src: 'audio/music.mp3', durationInSeconds: d }
}

// sound effects: public/audio/sfx/<name>.mp3 — a missing file is simply skipped
const sfx = {}
for (const f of list('audio/sfx', ['.mp3', '.wav', '.m4a'], 64)) {
  const d = probeAudio(join(PUB, 'audio/sfx', f))
  if (d) sfx[f.replace(/\.[^.]+$/, '')] = { src: `audio/sfx/${f}`, durationInSeconds: d }
}

const body = `// GENERATED by scripts/assets.mjs — do not edit. Re-run \`npm run assets\`.
export type ClipInfo = { src: string; width: number; height: number; durationInFrames: number }
export const STILLS: Record<string, string> = ${JSON.stringify(stills, null, 2)}
export const CLIPS: Record<string, ClipInfo> = ${JSON.stringify(clips, null, 2)}
export const MUSIC: { src: string; durationInSeconds: number } | null = ${JSON.stringify(music)}
export const SFX_FILES: Record<string, { src: string; durationInSeconds: number }> = ${JSON.stringify(sfx, null, 2)}
`
writeFileSync(join(ROOT, 'src', 'assets.gen.ts'), body)
console.log(
  `assets: ${Object.keys(stills).length} stills [${Object.keys(stills).join(', ')}], ` +
    `${Object.keys(clips).length} clips [${Object.keys(clips).join(', ')}], music: ${music ? 'yes' : 'no'}, sfx: [${Object.keys(sfx).join(', ')}]`,
)
